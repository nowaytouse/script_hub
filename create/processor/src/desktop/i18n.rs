#[cfg(test)]
mod tests {
    use super::{ALL_TEXT, Text, text};
    use crate::desktop::settings::Language;

    #[test]
    fn every_catalog_entry_is_nonempty_in_all_languages() {
        for key in ALL_TEXT {
            for language in [Language::En, Language::ZhCn, Language::Ja] {
                assert!(
                    !text(language, *key).trim().is_empty(),
                    "missing translation for {key:?} in {language:?}"
                );
            }
        }
    }

    #[test]
    fn system_language_resolves_before_lookup() {
        assert_eq!(text(Language::En, Text::Overview), "Overview");
        assert_eq!(text(Language::ZhCn, Text::Overview), "概览");
        assert_eq!(text(Language::Ja, Text::Overview), "概要");
        assert!(!text(Language::System, Text::Overview).trim().is_empty());
    }
}
