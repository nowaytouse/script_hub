use super::settings::Language;

macro_rules! catalog {
    ($( $key:ident => [$en:literal, $zh:literal, $ja:literal], )+) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum Text {
            $( $key, )+
        }

        pub fn text(language: Language, key: Text) -> &'static str {
            let translations = match key {
                $( Text::$key => [$en, $zh, $ja], )+
            };
            match language.resolved() {
                Language::En => translations[0],
                Language::ZhCn => translations[1],
                Language::Ja => translations[2],
                Language::System => unreachable!("Language::resolved returns a concrete language"),
            }
        }

        #[cfg(test)]
        const ALL_TEXT: &[Text] = &[$( Text::$key, )+];
    };
}

