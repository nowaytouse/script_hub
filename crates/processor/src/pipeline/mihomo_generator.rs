//! Render the common, policy-neutral subset as a Mihomo classical provider.

use crate::promax::rule::{RuleKind, SurgeRule};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

const OWNER: &str = "# Generated by Script Hub Mihomo generator\n";

/// A nonempty provider. `omitted` counts omitted source lines; `adapted` counts
/// source lines whose extended matching was reduced to a basic matcher.
#[derive(Debug, PartialEq, Eq)]
pub struct Rendered {
    pub content: String,
    pub supported: usize,
    pub omitted: usize,
    pub adapted: usize,
}

// Rust and Go regular expressions are not identical; accept only a small
// shared grammar until a target-core validator can check the full syntax.
fn portable_regex(value: &str) -> bool {
    let mut chars = value.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            if chars.next() != Some('.') {
                return false;
            }
        } else if !(c.is_ascii_alphanumeric() || "._-^$*+?".contains(c)) {
            return false;
        }
    }
    regex::Regex::new(value).is_ok()
}

/// Returns no artifact when there are no representable rules. Malformed rules,
/// policies and unsupported options fail the entire input rather than being lost.
pub fn render_classical(input: &str) -> Result<Option<Rendered>, String> {
    let mut rules = BTreeSet::new();
    let mut omitted = 0;
    let mut adapted = 0;
    for (index, line) in input.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with("//") {
            continue;
        }
        let rule = SurgeRule::parse(line)
            .map_err(|error| format!("invalid rule on line {}: {error}", index + 1))?;
        if rule.policy.is_some() {
            return Err(format!("policy in rule on line {}", index + 1));
        }
        let ip = matches!(
            rule.kind,
            RuleKind::IpCidr | RuleKind::IpCidr6 | RuleKind::IpAsn | RuleKind::GeoIp
        );
        let domain = matches!(
            rule.kind,
            RuleKind::Domain
                | RuleKind::DomainSuffix
                | RuleKind::DomainKeyword
                | RuleKind::DomainWildcard
        );
        if rule.options.iter().any(|option| match option.as_str() {
            "NO-RESOLVE" => !ip,
            "EXTENDED-MATCHING" => !domain && rule.kind != RuleKind::UrlRegex,
            _ => true,
        }) {
            return Err(format!("unsupported rule option on line {}", index + 1));
        }
        let common = matches!(
            rule.kind,
            RuleKind::Domain
                | RuleKind::DomainSuffix
                | RuleKind::DomainKeyword
                | RuleKind::DomainWildcard
                | RuleKind::DomainRegex
                | RuleKind::IpCidr
                | RuleKind::IpCidr6
                | RuleKind::IpAsn
                | RuleKind::GeoIp
                | RuleKind::ProcessName
        );
        // Mihomo's parser is comma-delimited; don't reinterpret quoted Surge
        // payloads or path-like process names as equivalent matchers.
        let representable = common
            && !rule.payload.contains(',')
            && !rule.payload.chars().any(char::is_control)
            && !(rule.kind == RuleKind::ProcessName
                && rule.payload.contains(['/', '\\', '*', '?']))
            && !(rule.kind == RuleKind::DomainWildcard && rule.payload.contains(['[', ']']))
            && !(rule.kind == RuleKind::DomainRegex && !portable_regex(&rule.payload))
            && !(rule.kind == RuleKind::IpAsn
                && !rule.payload.bytes().all(|byte| byte.is_ascii_digit()));
        if !representable {
            omitted += 1;
            continue;
        }
        let mut rendered = format!("{},{}", rule.kind.as_str(), rule.payload);
        if rule.options.iter().any(|option| option == "NO-RESOLVE") {
            rendered.push_str(",no-resolve");
        }
        if rule
            .options
            .iter()
            .any(|option| option == "EXTENDED-MATCHING")
        {
            adapted += 1;
        }
        rules.insert(rendered);
    }
    if rules.is_empty() {
        return Ok(None);
    }
    let supported = rules.len();
    let mut content = String::from("payload:\n");
    for rule in rules {
        content.push_str("  - '");
        content.push_str(&rule.replace('\'', "''"));
        content.push_str("'\n");
    }
    Ok(Some(Rendered {
        content,
        supported,
        omitted,
        adapted,
    }))
}

fn plan(root: &Path) -> Result<BTreeMap<PathBuf, String>, String> {
    let mut outputs = BTreeMap::new();
    let mut source_count = 0;
    for (source, destination) in [
        (root.join("rulesets/RULE-SET"), root.join("rulesets/Mihomo")),
        (
            root.join("rulesets/AdBlock"),
            root.join("rulesets/AdBlock/Mihomo"),
        ),
    ] {
        let entries =
            fs::read_dir(&source).map_err(|e| format!("cannot list {}: {e}", source.display()))?;
        for entry in entries {
            let entry =
                entry.map_err(|e| format!("cannot read {} entry: {e}", source.display()))?;
            let path = entry.path();
            if path.extension().is_none_or(|extension| extension != "list") {
                continue;
            }
            let kind = entry
                .file_type()
                .map_err(|e| format!("cannot inspect {}: {e}", path.display()))?;
            if !kind.is_file() {
                return Err(format!("not a regular source file: {}", path.display()));
            }
            let name = path
                .file_stem()
                .and_then(|s| s.to_str())
                .ok_or_else(|| format!("invalid source name: {}", path.display()))?;
            if name.ends_with("_sources") {
                continue;
            }
            source_count += 1;
            let input = fs::read_to_string(&path)
                .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
            if let Some(rendered) =
                render_classical(&input).map_err(|e| format!("{}: {e}", path.display()))?
            {
                let suffix = if rendered.omitted == 0 && rendered.adapted == 0 {
                    ""
                } else {
                    "_supported"
                };
                let target = destination.join(format!("{name}{suffix}.yaml"));
                let content = format!(
                    "{OWNER}# Supported: {}\n# Omitted: {}\n# Adapted: {}\n{}",
                    rendered.supported, rendered.omitted, rendered.adapted, rendered.content
                );
                if outputs.insert(target.clone(), content).is_some() {
                    return Err(format!("conflicting output: {}", target.display()));
                }
            }
        }
    }
    if source_count == 0 {
        return Err("no Mihomo source files; preserving outputs".into());
    }
    if outputs.is_empty() {
        return Err("no representable Mihomo rules; preserving outputs".into());
    }
    Ok(outputs)
}

// Only files carrying the generator's ownership marker are eligible for pruning.
fn existing(root: &Path) -> Result<BTreeMap<PathBuf, String>, String> {
    let mut outputs = BTreeMap::new();
    for dir in [
        root.join("rulesets/Mihomo"),
        root.join("rulesets/AdBlock/Mihomo"),
    ] {
        match fs::symlink_metadata(&dir) {
            Ok(metadata) if !metadata.file_type().is_dir() => {
                return Err(format!("not a regular output directory: {}", dir.display()));
            }
            Ok(_) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                crate::verify_missing_directory(&dir)?;
                continue;
            }
            Err(error) => return Err(format!("cannot inspect {}: {error}", dir.display())),
        }
        let entries = match fs::read_dir(&dir) {
            Ok(entries) => entries,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                crate::verify_missing_directory(&dir)?;
                continue;
            }
            Err(e) => return Err(format!("cannot list {}: {e}", dir.display())),
        };
        for entry in entries {
            let entry = entry.map_err(|e| format!("cannot read {} entry: {e}", dir.display()))?;
            let path = entry.path();
            if path.extension().is_none_or(|extension| extension != "yaml") {
                continue;
            }
            let kind = entry
                .file_type()
                .map_err(|e| format!("cannot inspect {}: {e}", path.display()))?;
            if !kind.is_file() {
                return Err(format!("not a regular output file: {}", path.display()));
            }
            let content = fs::read_to_string(&path)
                .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
            outputs.insert(path, content);
        }
    }
    Ok(outputs)
}

/// Validate all inputs and destinations before atomic per-file publication.
pub fn run_generator(root: &Path) -> Result<usize, String> {
    let planned = plan(root)?;
    let old = existing(root)?;
    for (path, content) in &old {
        if !content.starts_with(OWNER) {
            return Err(format!(
                "unexpected or unowned Mihomo file: {}",
                path.display()
            ));
        }
    }
    for (path, content) in &planned {
        if old.get(path) == Some(content) {
            continue;
        }
        let parent = path
            .parent()
            .ok_or_else(|| format!("missing parent: {}", path.display()))?;
        fs::create_dir_all(parent)
            .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
        crate::filesystem::replace_file(path, content.as_bytes())
            .map_err(|e| format!("cannot publish {}: {e}", path.display()))?;
    }
    for (path, content) in old {
        if content.starts_with(OWNER) && !planned.contains_key(&path) {
            fs::remove_file(&path)
                .map_err(|e| format!("cannot remove stale {}: {e}", path.display()))?;
        }
    }
    Ok(planned.len())
}

/// Recompute the expected outputs and reject missing, altered or stale owned files.
pub fn validate_generated(root: &Path) -> Result<usize, String> {
    let planned = plan(root)?;
    let old = existing(root)?;
    for (path, expected) in &planned {
        if old.get(path) != Some(expected) {
            return Err(format!(
                "missing or mismatched Mihomo output: {}",
                path.display()
            ));
        }
    }
    for path in old.keys() {
        if !planned.contains_key(path) {
            return Err(format!("unexpected Mihomo output: {}", path.display()));
        }
    }
    Ok(planned.len())
}

#[cfg(test)]
mod tests {
    use super::{OWNER, render_classical, run_generator, validate_generated};
    use std::fs;

    #[test]
    fn renders_sorted_deduplicated_yaml_and_keeps_no_resolve() {
        let output = render_classical("IP-ASN,13335,no-resolve\nDOMAIN,z.example\nDOMAIN,a.example\nDOMAIN,z.example\nIP-CIDR,192.0.2.0/24,no-resolve\n").unwrap().unwrap();
        assert_eq!(output.supported, 4);
        assert_eq!(output.omitted, 0);
        assert_eq!(output.adapted, 0);
        assert_eq!(
            output.content,
            "payload:\n  - 'DOMAIN,a.example'\n  - 'DOMAIN,z.example'\n  - 'IP-ASN,13335,no-resolve'\n  - 'IP-CIDR,192.0.2.0/24,no-resolve'\n"
        );
    }

    #[test]
    fn marks_unsupported_matchers_and_never_emits_empty_provider() {
        let output = render_classical(
            "USER-AGENT,foo*\nDOMAIN,a.example\nURL-REGEX,^https://example\\.test\n",
        )
        .unwrap()
        .unwrap();
        assert_eq!((output.supported, output.omitted), (1, 2));
        assert!(
            render_classical("# only comment\nUSER-AGENT,foo*\n")
                .unwrap()
                .is_none()
        );
    }

    #[test]
    fn rejects_policies_invalid_options_and_invalid_rules() {
        for input in [
            "DOMAIN,a.example,DIRECT",
            "IP-CIDR,192.0.2.0/24,extended-matching",
            "DOMAIN,a.example,pre-matching",
            "IP-CIDR,300.0.0.0/8",
            "UNKNOWN,a",
        ] {
            assert!(render_classical(input).is_err(), "{input}");
        }
    }

    #[test]
    fn quotes_yaml_and_omits_unsafe_payloads() {
        let output = render_classical(
            "PROCESS-NAME,foo'bar\nPROCESS-NAME,/path/to/app\nDOMAIN-REGEX,\"^a{1,3}\\.test$\"\n",
        )
        .unwrap()
        .unwrap();
        assert_eq!(output.omitted, 2);
        assert!(output.content.contains("'PROCESS-NAME,foo''bar'"));
    }

    #[test]
    fn wildcard_character_classes_are_labeled_as_omitted() {
        let output = render_classical("DOMAIN,a.example\nDOMAIN-WILDCARD,foo[0-9].example\n")
            .unwrap()
            .unwrap();
        assert_eq!((output.supported, output.omitted), (1, 1));
        assert!(!output.content.contains("WILDCARD"));
    }

    #[test]
    fn process_name_wildcards_are_marked_as_omitted() {
        let output =
            render_classical("PROCESS-NAME,Firefox\nPROCESS-NAME,Google*\nPROCESS-NAME,app?.exe\n")
                .unwrap()
                .unwrap();
        assert_eq!((output.supported, output.omitted), (1, 2));
        assert!(!output.content.contains("Google*"));
        assert!(!output.content.contains("app?.exe"));
    }

    #[test]
    fn extended_matching_projects_basic_rule_and_counts_adaptations() {
        let output = render_classical("DOMAIN,a.example,extended-matching\nDOMAIN-SUFFIX,b.example,extended-matching\nIP-CIDR,192.0.2.0/24,no-resolve\n").unwrap().unwrap();
        assert_eq!(
            (output.supported, output.omitted, output.adapted),
            (3, 0, 2)
        );
        assert!(output.content.contains("'DOMAIN,a.example'"));
        assert!(output.content.contains("'DOMAIN-SUFFIX,b.example'"));
        assert!(output.content.contains("'IP-CIDR,192.0.2.0/24,no-resolve'"));
        assert!(!output.content.contains("extended-matching"));
    }

    #[test]
    fn unsupported_url_regex_with_extended_matching_is_omitted() {
        let output = render_classical(
            "DOMAIN,a.example\nURL-REGEX,^https://example\\.test,extended-matching\n",
        )
        .unwrap()
        .unwrap();
        assert_eq!(
            (output.supported, output.omitted, output.adapted),
            (1, 1, 0)
        );
    }

    #[test]
    fn publication_checks_ownership_staleness_and_failed_input() {
        let root = std::env::temp_dir().join(format!(
            "mihomo-generator-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let sources = root.join("rulesets/RULE-SET");
        let adblock = root.join("rulesets/AdBlock");
        fs::create_dir_all(&sources).unwrap();
        fs::create_dir_all(&adblock).unwrap();
        fs::write(
            sources.join("example.list"),
            "DOMAIN,a.example\nUSER-AGENT,foo*\n",
        )
        .unwrap();
        assert_eq!(run_generator(&root).unwrap(), 1);
        assert_eq!(validate_generated(&root).unwrap(), 1);
        let out = root.join("rulesets/Mihomo/example_supported.yaml");
        let before = fs::read_to_string(&out).unwrap();
        assert!(before.starts_with(OWNER));
        fs::write(sources.join("bad.list"), "DOMAIN,invalid/name\n").unwrap();
        assert!(run_generator(&root).is_err());
        assert_eq!(fs::read_to_string(&out).unwrap(), before);
        fs::remove_file(sources.join("bad.list")).unwrap();
        fs::write(sources.join("example.list"), "DOMAIN,a.example\n").unwrap();
        assert!(validate_generated(&root).is_err());
        assert_eq!(run_generator(&root).unwrap(), 1);
        assert!(!out.exists());
        let new_out = root.join("rulesets/Mihomo/example.yaml");
        fs::write(&new_out, "user data\n").unwrap();
        assert!(run_generator(&root).is_err());
        assert_eq!(fs::read_to_string(&new_out).unwrap(), "user data\n");
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn empty_plan_and_unexpected_unowned_yaml_fail_without_removing_data() {
        let root = std::env::temp_dir().join(format!(
            "mihomo-generator-fail-closed-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let sources = root.join("rulesets/RULE-SET");
        let adblock = root.join("rulesets/AdBlock");
        fs::create_dir_all(&sources).unwrap();
        fs::create_dir_all(&adblock).unwrap();
        let source = sources.join("example.list");
        fs::write(&source, "DOMAIN,a.example\n").unwrap();
        run_generator(&root).unwrap();
        let published = root.join("rulesets/Mihomo/example.yaml");
        let original = fs::read_to_string(&published).unwrap();

        for input in ["# empty\n", "USER-AGENT,foo*\n"] {
            fs::write(&source, input).unwrap();
            assert!(run_generator(&root).is_err());
            assert!(validate_generated(&root).is_err());
            assert_eq!(fs::read_to_string(&published).unwrap(), original);
        }

        fs::write(&source, "DOMAIN,a.example\n").unwrap();
        let unknown = root.join("rulesets/Mihomo/legacy.yaml");
        fs::write(&unknown, "user data\n").unwrap();
        assert!(run_generator(&root).is_err());
        assert!(validate_generated(&root).is_err());
        assert_eq!(fs::read_to_string(&unknown).unwrap(), "user data\n");
        assert_eq!(fs::read_to_string(&published).unwrap(), original);
        fs::remove_file(&unknown).unwrap();
        fs::write(&source, "DOMAIN,a.example,extended-matching\n").unwrap();
        assert_eq!(run_generator(&root).unwrap(), 1);
        assert!(!published.exists());
        let adapted = root.join("rulesets/Mihomo/example_supported.yaml");
        assert!(
            fs::read_to_string(adapted)
                .unwrap()
                .contains("# Adapted: 1\n")
        );
        assert_eq!(validate_generated(&root).unwrap(), 1);
        fs::remove_dir_all(root).unwrap();
    }
}
