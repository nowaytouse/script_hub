type ParsedSections = Vec<(String, Vec<(usize, String)>)>;
fn parse_sections(text: &str) -> ParsedSections {
    let mut output: ParsedSections = Vec::new();
    for (index, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if let Some(name) = line.strip_prefix('[').and_then(|s| s.strip_suffix(']')) {
            output.push((name.into(), Vec::new()));
        } else if !line.is_empty()
            && !line.starts_with(['#', ';'])
            && !line.starts_with("//")
            && let Some((_, rows)) = output.last_mut()
        {
            rows.push((index + 1, line.into()));
        }
    }
    output
}

/// Split fields without treating commas inside quoted regexes or logical groups as separators.
fn fields(text: &str) -> Option<Vec<String>> {
    let logical = ["AND,", "OR,", "NOT,", "("]
        .iter()
        .any(|p| text.trim_start().starts_with(p));
    let mut result = Vec::new();
    let mut current = String::new();
    let mut quoted = false;
    let mut escaped = false;
    let mut depth = 0usize;
    for c in text.chars() {
        if escaped {
            current.push(c);
            escaped = false;
            continue;
        }
        if c == '\\' {
            current.push(c);
            escaped = true;
            continue;
        }
        if c == '"' {
            quoted = !quoted;
            current.push(c);
            continue;
        }
        if !quoted {
            if logical {
                match c {
                    '(' => depth += 1,
                    ')' => depth = depth.checked_sub(1)?,
                    _ => {}
                }
            }
            if c == ',' && depth == 0 {
                result.push(unquote_field(&current));
                current.clear();
                continue;
            }
        }
        current.push(c);
    }
    if quoted || depth != 0 {
        return None;
    }
    result.push(unquote_field(&current));
    Some(result)
}
fn unquote_field(value: &str) -> String {
    let value = value.trim();
    value
        .strip_prefix('"')
        .and_then(|s| s.strip_suffix('"'))
        .unwrap_or(value)
        .to_owned()
}
fn quoted_field(value: &str) -> String {
    if value.contains(',') || value.chars().any(char::is_whitespace) {
        format!("\"{}\"", value.replace('"', "\\\""))
    } else {
        value.into()
    }
}
fn policy(value: &str) -> Option<&str> {
    match value {
        "DIRECT" => Some("DIRECT"),
        "REJECT-DROP" => Some("REJECT-DROP"),
        "REJECT" | "REJECT-NO-DROP" | "REJECT-TINYGIF" | "REJECT-IMG" | "REJECT-DICT"
        | "REJECT-ARRAY" | "REJECT-200" => Some("REJECT"),
        _ => None,
    }
}
fn leaf(parts: &[String], nested: bool) -> Option<String> {
    if parts.len() != 2 || parts[1].is_empty() {
        return None;
    }
    let kind = parts[0].as_str();
    if matches!(kind, "AND" | "OR" | "NOT") {
        let group = parts[1].strip_prefix('(')?.strip_suffix(')')?;
        let children = fields(group)?;
        if children.is_empty() || kind == "NOT" && children.len() != 1 {
            return None;
        }
        let children = children
            .iter()
            .map(|child| {
                let child = child.strip_prefix('(')?.strip_suffix(')')?;
                Some(format!("({})", leaf(&fields(child)?, true)?))
            })
            .collect::<Option<Vec<_>>>()?;
        return Some(format!("{kind},({})", children.join(",")));
    }
    if kind == "PROTOCOL" {
        return (nested && matches!(parts[1].as_str(), "TCP" | "UDP"))
            .then(|| format!("PROTOCOL,{}", parts[1]));
    }
    let kind = match kind {
        "DOMAIN" | "DOMAIN-SUFFIX" | "DOMAIN-KEYWORD" | "DOMAIN-WILDCARD" | "IP-CIDR"
        | "IP-CIDR6" | "SRC-IP-CIDR" | "SRC-PORT" | "IN-PORT" | "PROCESS-NAME" => kind,
        "SRC-IP" => "SRC-IP-CIDR",
        "DEST-PORT" | "DST-PORT" => "DEST-PORT",
        _ => return None,
    };
    Some(format!("{kind},{}", quoted_field(&parts[1])))
}
fn emit_rule(
    line: &str,
    number: usize,
    report: &mut Projection,
    output: &mut BTreeMap<String, Vec<String>>,
) {
    let Some(parts) = fields(line) else {
        report.note(number, "Rule", "omitted", "unbalanced rule fields");
        return;
    };
    if parts.len() < 3 {
        report.note(
            number,
            "Rule",
            "omitted",
            "rule needs matcher, payload and a supported built-in policy",
        );
        return;
    }
    let Some(target_policy) = policy(&parts[2]) else {
        report.note(number, "Rule", "omitted", "unsupported named/group policy");
        return;
    };
    if parts[0] == "URL-REGEX" {
        let action = match parts[2].as_str() {
            "REJECT-IMG" | "REJECT-TINYGIF" => "reject-img",
            "REJECT-DICT" => "reject-dict",
            "REJECT-ARRAY" => "reject-array",
            "REJECT-200" => "reject-200",
            "DIRECT" => {
                report.note(
                    number,
                    "Rule",
                    "omitted",
                    "URL-REGEX DIRECT cannot become a rejecting rewrite",
                );
                return;
            }
            _ => "reject",
        };
        if parts[1].chars().any(char::is_whitespace) {
            report.note(
                number,
                "Rule",
                "omitted",
                "URL regex contains whitespace unsupported by native rewrite tokenization",
            );
            return;
        }
        output
            .entry("URL Rewrite".into())
            .or_default()
            .push(format!("{} {action}", parts[1]));
        report.note(
            number,
            "Rule",
            "adapted",
            "URL-REGEX converted to native URL Rewrite",
        );
        return;
    }
    let Some(matcher) = leaf(&parts[..2], false) else {
        report.note(
            number,
            "Rule",
            "omitted",
            format!(
                "unsupported matcher {} (use the main Mihomo providers where applicable)",
                parts[0]
            ),
        );
        return;
    };
    let keep_no_resolve = matches!(parts[0].as_str(), "IP-CIDR" | "IP-CIDR6")
        && parts[3..]
            .iter()
            .any(|o| o.eq_ignore_ascii_case("no-resolve"));
    let dropped = parts[3..]
        .iter()
        .filter(|o| !(keep_no_resolve && o.eq_ignore_ascii_case("no-resolve")))
        .cloned()
        .collect::<Vec<_>>();
    if !dropped.is_empty() {
        report.note(
            number,
            "Rule",
            "adapted",
            format!(
                "importer does not preserve rule options: {}",
                dropped.join(",")
            ),
        );
    }
    if target_policy != parts[2] {
        report.note(
            number,
            "Rule",
            "adapted",
            format!("{} becomes {target_policy} in the importer", parts[2]),
        );
    }
    output.entry("Rule".into()).or_default().push(format!(
        "{matcher},{target_policy}{}",
        if keep_no_resolve { ",no-resolve" } else { "" }
    ));
}
fn script(line: &str, number: usize, report: &mut Projection) -> Option<String> {
    let (name, parameters) = line.split_once('=')?;
    let mut values = Vec::new();
    for field in crate::smart_cleanup::split_script_parameters(parameters) {
        let (key, value) = field.split_once('=')?;
        if values.iter().any(|(existing, _)| *existing == key.trim()) {
            report.note(
                number,
                "Script",
                "omitted",
                "duplicate script parameter requires explicit review",
            );
            return None;
        }
        values.push((key.trim(), value.trim()));
    }
    let value = |key| {
        values
            .iter()
            .find_map(|(k, v)| (*k == key).then_some(v.trim_matches(['\'', '"'])))
    };
    let kind = value("type")?;
    if value("enable") == Some("false") {
        report.note(number, "Script", "omitted", "disabled script");
        return None;
    }
    if !matches!(
        kind,
        "http-request" | "http-response" | "cron" | "event" | "generic"
    ) {
        report.note(
            number,
            "Script",
            "omitted",
            format!("unsupported script type {kind}"),
        );
        return None;
    }
    let path = value("script-path")?.trim_matches(['\'', '"']);
    if !path.starts_with("https://") {
        report.note(
            number,
            "Script",
            "omitted",
            "remote module requires an HTTPS script resource, not a local attachment",
        );
        return None;
    }
    if kind.starts_with("http-") && value("pattern").is_none()
        || kind == "cron" && value("cronexp").is_none()
    {
        report.note(
            number,
            "Script",
            "omitted",
            "missing required pattern/cronexp",
        );
        return None;
    }
    if kind == "event"
        && !matches!(
            value("event-name"),
            Some("network-changed" | "engine-started" | "profile-reloaded")
        )
    {
        report.note(number, "Script", "omitted", "unsupported event-name");
        return None;
    }
    let allowed = [
        "type",
        "pattern",
        "cronexp",
        "event-name",
        "script-path",
        "requires-body",
        "binary-body-mode",
        "max-size",
        "timeout",
        "full-header-mode",
        "argument",
        "enable",
    ];
    let mut kept = Vec::new();
    for (key, value) in values {
        if allowed.contains(&key) {
            kept.push(format!("{key}={value}"));
        } else {
            report.note(
                number,
                "Script",
                "adapted",
                format!("importer does not forward script field {key}"),
            );
        }
    }
    Some(format!("{} = {}", name.trim(), kept.join(", ")))
}
fn tokens(line: &str) -> Option<Vec<String>> {
    let mut values = Vec::new();
    let mut current = String::new();
    let mut quote = None;
    let mut escaped = false;
    for c in line.chars() {
        if escaped {
            current.push(c);
            escaped = false;
            continue;
        }
        if c == '\\' && quote.is_some() {
            current.push(c);
            escaped = true;
            continue;
        }
        if let Some(q) = quote {
            if c == q {
                quote = None;
            } else {
                current.push(c);
            }
        } else if c == '\'' || c == '"' {
            quote = Some(c);
        } else if c.is_whitespace() {
            if !current.is_empty() {
                values.push(std::mem::take(&mut current));
            }
        } else {
            current.push(c);
        }
    }
    if quote.is_some() {
        return None;
    }
    if !current.is_empty() {
        values.push(current);
    }
    Some(values)
}
fn map_local(line: &str) -> Option<String> {
    let values = tokens(line)?;
    let get = |key: &str| values.iter().find_map(|v| v.strip_prefix(key));
    if get("data-type=") == Some("tiny-gif") {
        if get("data=").is_some() {
            return None;
        }
        let mut result = quoted_field(values.first()?);
        for item in values.iter().skip(1) {
            let (key, value) = item.split_once('=')?;
            if key == "data-type" {
                result.push_str(r#" data-type=base64 data="R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7""#);
            } else {
                result.push_str(&format!(" {key}=\"{value}\""));
            }
        }
        if get("header=").is_none() {
            result.push_str(r#" header="Content-Type:image/gif""#);
        }
        return Some(result);
    }
    let data = get("data=")?;
    let supported = match get("data-type=").unwrap_or("file") {
        "file" => data.starts_with("https://"),
        "text" | "base64" => true,
        _ => false,
    };
    supported.then(|| line.to_owned())
}

/// Project a public Surge artifact into the pinned preview importer's supported input.
fn argument_defaults(source: &str) -> Result<BTreeMap<String, String>, String> {
    let meta = crate::merge_bundles::module_metadata_pub(source);
    let mut defaults = BTreeMap::new();
    if let Some(arguments) = meta.get("arguments") {
        for field in crate::smart_cleanup::split_script_parameters(arguments) {
            let (key, value) = field
                .split_once(':')
                .ok_or("invalid public argument default")?;
            let value = value.trim();
            let value = if value.starts_with('"') {
                serde_json::from_str::<String>(value)
                    .map_err(|_| "invalid quoted argument default")?
            } else {
                value.trim_matches('\'').into()
            };
            if defaults.insert(key.trim().to_owned(), value).is_some() {
                return Err("duplicate public argument default".into());
            }
        }
    }
    Ok(defaults)
}
fn resolve_defaults(line: &str, defaults: &BTreeMap<String, String>) -> Option<String> {
    let mut rest = line;
    let mut out = String::new();
    while let Some((before, tail)) = rest.split_once("{{{") {
        let (key, after) = tail.split_once("}}}")?;
        out.push_str(before);
        out.push_str(defaults.get(key)?);
        rest = after;
    }
    out.push_str(rest);
    (!out.contains("{{{") && !out.contains("}}}")).then_some(out)
}

pub fn render(source: &str) -> Result<Projection, String> {
    render_embedded(source, &[])
}

fn render_embedded(source: &str, routing: &[RoutingReport]) -> Result<Projection, String> {
    let errors = crate::promax::validation::validate_surge_module(source);
    if !errors.is_empty() {
        return Err(format!(
            "source module is invalid: line {} {}",
            errors[0].line, errors[0].code
        ));
    }
    let defaults = argument_defaults(source)?;
    let parsed = parse_sections(source);
    let inline: BTreeMap<_, _> = parsed
        .iter()
        .filter_map(|(name, rows)| name.strip_prefix("Ruleset ").map(|name| (name, rows)))
        .collect();
    let mut report = Projection {
        content: String::new(),
        input_lines: parsed.iter().map(|(_, rows)| rows.len()).sum(),
        emitted_lines: 0,
        active_lines: 0,
        sections: BTreeMap::new(),
        diagnostics: Vec::new(),
    };
    let mut output: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (section, rows) in &parsed {
        if section.starts_with("Ruleset ") {
            continue;
        }
        for (number, original) in rows {
            let Some(resolved) = resolve_defaults(original, &defaults) else {
                report.note(
                    *number,
                    section,
                    "omitted",
                    "unresolved argument placeholder has no public source default",
                );
                continue;
            };
            let line = original;
            if resolved.trim_start().starts_with('#') {
                report.note(*number,section,"parameterized","source argument default comments this entry; retained for native parameter UI, not enabled by this generator");
            }
            match section.as_str() {
                "Rule"=>{
                    let parts=fields(line).ok_or_else(||format!("invalid source rule on line {number}"))?;
                    if parts.first().is_some_and(|p|p=="RULE-SET") {
                        if let Some(embedded) = routing.iter().find(|r| r.source_rule_line == *number) {
                            for (name, rows) in parse_sections(&embedded.projection.content) {
                                output.entry(name).or_default().extend(rows.into_iter().map(|(_, row)|row));
                            }
                            report.input_lines += embedded.projection.input_lines;
                            report.note(*number, section, "adapted", format!("embedded public PROMAX list {} at its source declaration; per-source compatibility is recorded in the catalog", embedded.source));
                        } else if let Some(rows)=parts.get(1).and_then(|name|inline.get(name.as_str())) {
                            let policy=parts.get(2).ok_or("inline ruleset lacks policy")?;
                            let parent_no_resolve = parts[3..]
                                .iter()
                                .any(|option| option.eq_ignore_ascii_case("no-resolve"));
                            let mut discarded_options = Vec::new();
                            let mut seen_options = BTreeSet::new();
                            for option in &parts[3..] {
                                if !option.eq_ignore_ascii_case("no-resolve")
                                    && seen_options.insert(option.to_ascii_lowercase())
                                {
                                    discarded_options.push(option.as_str());
                                }
                            }
                            if !discarded_options.is_empty() {
                                report.note(
                                    *number,
                                    section,
                                    "adapted",
                                    format!(
                                        "parent RULE-SET options are not preserved: {}",
                                        discarded_options.join(",")
                                    ),
                                );
                            }
                            report.note(*number,section,"adapted",format!("expanded local inline ruleset {} ({} rows)",parts[1],rows.len()));
                            for (n,row) in *rows {
                                let expanded=format!("{row},{policy}");
                                // Inline rows have no policy; preserve member options and inherit
                                // the parent's no-resolve only where the importer can retain it.
                                let mut child=fields(&expanded).ok_or("malformed inline rule")?;
                                if child.len()>3 {let last=child.pop().expect("policy");child.insert(2,last);}
                                if parent_no_resolve
                                    && child.first().is_some_and(|kind| {
                                        matches!(kind.as_str(), "IP-CIDR" | "IP-CIDR6")
                                    })
                                    && !child.iter().skip(3).any(|option| {
                                        option.eq_ignore_ascii_case("no-resolve")
                                    })
                                {
                                    child.push("no-resolve".into());
                                }
                                emit_rule(&child.iter().map(|s|quoted_field(s)).collect::<Vec<_>>().join(","),*n,&mut report,&mut output);
                            }
                        }else{report.note(*number,section,"omitted","external RULE-SET is unsupported by this standalone projection; only the source-declared public PROMAX lists are embedded by the repository generator");}
                    }else{emit_rule(line,*number,&mut report,&mut output);}
                }
                "IP Rewrite"=>report.note(*number,section,"omitted","FlClash importer has no IP Rewrite section; equivalent IP-CIDR fallback rules, where present, remain in Rule output"),
                "Script"=>{let before=report.diagnostics.len();if let Some(value)=script(line,*number,&mut report){output.entry(section.clone()).or_default().push(value);}else if report.diagnostics.len()==before {report.note(*number,section,"omitted","malformed or unsupported script parameters");}},
                "MITM"=>{
                    if let Some((key,value))=line.split_once('=') && key.trim()=="hostname" {
                        let mut hosts=Vec::new();let mut prefix="%APPEND%";
                        let value=value.trim();let value=if let Some(v)=value.strip_prefix("%INSERT%"){prefix="%INSERT%";v}else{value.strip_prefix("%APPEND%").unwrap_or(value)};
                        for host in value.split(',').map(str::trim).filter(|s|!s.is_empty()) {
                            if host.starts_with('-') || !crate::mitm_manager::is_restricted(host){hosts.push(host);}else{report.note(*number,section,"omitted",format!("restricted MITM host {host}"));}
                        }
                        if !hosts.is_empty(){output.entry(section.clone()).or_default().push(format!("hostname = {prefix} {}",hosts.join(", ")));}
                    }else{report.note(*number,section,"omitted","importer only accepts hostname; certificate and global MITM settings are never published");}
                }
                "Map Local"=>{if let Some(converted)=map_local(line){if converted!=*line{report.note(*number,section,"adapted","tiny-gif replaced with an embedded 1x1 GIF base64 response");}output.entry(section.clone()).or_default().push(converted);}else{report.note(*number,section,"omitted","unsupported Map Local data type or file resource without a public HTTPS URL");}},
                "Body Rewrite" if line.starts_with("http-request-jq ")||line.starts_with("http-response-jq ")=>report.note(*number,section,"omitted","jq body rewrite is not supported by the preview importer"),
                "URL Rewrite"|"Header Rewrite"|"Body Rewrite"=>{
                    if line.starts_with("http-request if ") || line.starts_with("http-response if ") || line.contains(" json ") {
                        report.note(*number,section,"omitted","conditional or JSON-body syntax has no equivalent in the pinned importer");
                    }else{output.entry(section.clone()).or_default().push(line.clone());}
                }
                _=>report.note(*number,section,"omitted","section is not supported by the preview module importer; keep applicable settings in the main configuration"),
            }
        }
    }
    // Removing unsupported handlers must not leave unnecessary TLS interception behind.
    let functional_lines = output
        .iter()
        .filter(|(section, _)| !matches!(section.as_str(), "MITM" | "Rule"))
        .flat_map(|(_, rows)| rows.iter())
        .filter_map(|line| resolve_defaults(line, &defaults))
        .collect::<Vec<_>>();
    let patterns = crate::promax::safety::SafetyPolicy::functional_host_patterns(&functional_lines);
    let safety = crate::promax::safety::SafetyPolicy::default();
    if let Some(rows) = output.get_mut("MITM") {
        let mut kept_rows = Vec::new();
        for row in rows.iter() {
            let (_, value) = row
                .split_once('=')
                .ok_or("invalid projected MITM hostname")?;
            let value = value.trim();
            let (prefix, value) = if let Some(v) = value.strip_prefix("%INSERT%") {
                ("%INSERT%", v)
            } else {
                ("%APPEND%", value.strip_prefix("%APPEND%").unwrap_or(value))
            };
            let mut hosts = Vec::new();
            for host in value.split(',').map(str::trim).filter(|h| !h.is_empty()) {
                let resolved =
                    resolve_defaults(host, &defaults).ok_or("unresolved MITM argument")?;
                if host.starts_with('-')
                    || safety.hostname_is_referenced_by_patterns(&resolved, &patterns)
                {
                    hosts.push(host);
                } else {
                    report.note(
                        0,
                        "MITM",
                        "omitted",
                        format!("unreferenced hostname after projection: {host}"),
                    );
                }
            }
            if !hosts.is_empty() {
                kept_rows.push(format!("hostname = {prefix} {}", hosts.join(", ")));
            }
        }
        *rows = kept_rows;
    }
    let metadata = crate::merge_bundles::module_metadata_pub(source);
    let name = metadata.get("name").ok_or("source missing name")?;
    report.content = format!(
        "#!name=FlClash Preview · {name}\n#!desc=Native preview importer projection; see modules/flclash/catalog.json for compatibility omissions.\n{OWNER}\n# Importer contract: {CONTRACT_REVISION}\n# Scripts and HTTPS decryption require the user's explicit in-app review.\n# Third-party notices: https://github.com/nowaytouse/script_hub/blob/master/THIRD_PARTY_NOTICES.md\n# Source catalog: https://raw.githubusercontent.com/nowaytouse/script_hub/master/modules/flclash/catalog.json\n"
    );
    for key in [
        "author",
        "icon",
        "tag",
        "arguments",
        "arguments-desc",
        "system",
    ] {
        if let Some(v) = metadata.get(key) {
            report.content.push_str(&format!("#!{key}={v}\n"));
        }
    }
    if !routing.is_empty() {
        report.content.push_str(&routing_notices());
    }
    append_sections(&mut report, &mut output);
    if !routing.is_empty() {
        validate_merged_size(report.content.len())?;
    }
    Ok(report)
}

fn validate_merged_size(bytes: usize) -> Result<(), String> {
    if bytes > MAX_ROUTING_TOTAL_BYTES {
        return Err("merged PROMAX module exceeds the publication limit".into());
    }
    Ok(())
}

fn append_sections(report: &mut Projection, output: &mut BTreeMap<String, Vec<String>>) {
    for section in SECTIONS {
        if let Some(rows) = output.get_mut(*section) {
            let mut seen = BTreeSet::new();
            rows.retain(|row| seen.insert(row.clone()));
            if rows.is_empty() {
                continue;
            }
            report.sections.insert((*section).into(), rows.len());
            report.emitted_lines += rows.len();
            if *section != "MITM" {
                report.active_lines += rows.len();
            }
            report.content.push_str(&format!("\n[{section}]\n"));
            for row in rows {
                report.content.push_str(row);
                report.content.push('\n');
            }
        }
    }
}
fn relative(root: &Path, path: &Path) -> Result<String, String> {
    Ok(path
        .strip_prefix(root)
        .map_err(|_| "path escapes root")?
        .components()
        .map(|c| c.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/"))
}
fn encode(path: &str) -> String {
    path.split('/')
        .map(|s| utf8_percent_encode(s, NON_ALPHANUMERIC).to_string())
        .collect::<Vec<_>>()
        .join("/")
}
fn fingerprint(text: &str) -> String {
    format!("{:x}", md5::compute(text.as_bytes()))
}
fn read_public(root: &Path, path: &Path) -> Result<String, String> {
    read_public_bounded(root, path, 32 * 1024 * 1024)
}

fn read_public_bounded(root: &Path, path: &Path, limit: usize) -> Result<String, String> {
    for p in path.ancestors().take_while(|p| *p != root) {
        let m =
            fs::symlink_metadata(p).map_err(|e| format!("cannot inspect {}: {e}", p.display()))?;
        if m.file_type().is_symlink() {
            return Err(format!("symlink in public input: {}", p.display()));
        }
    }
    let m = fs::metadata(path).map_err(|e| e.to_string())?;
    if !m.is_file() || m.len() > limit as u64 {
        return Err(format!(
            "invalid or oversized public artifact {}",
            path.display()
        ));
    }
    // Git stores public text with LF even when core.autocrlf produces a CRLF
    // worktree. Fingerprints, source byte counts and output must use that same
    // canonical text on every platform; the raw file size was bounded above.
    let text = fs::read_to_string(path).map_err(|e| e.to_string())?;
    Ok(text.replace("\r\n", "\n"))
}

fn public_adblock_path(url: &str) -> Result<PathBuf, String> {
    let name = [
        "https://cdn.jsdelivr.net/gh/nowaytouse/script_hub@master/rulesets/AdBlock/",
        "https://raw.githubusercontent.com/nowaytouse/script_hub/master/rulesets/AdBlock/",
    ]
    .iter()
    .find_map(|prefix| url.strip_prefix(prefix))
    .ok_or("PROMAX routing source is not an approved public repository URL")?;
    if !name.starts_with("AdBlock_")
        || !name.ends_with(".list")
        || name.contains("..")
        || !name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-' | b'.'))
    {
        return Err("PROMAX routing source has an unsafe filename".into());
    }
    Ok(PathBuf::from("rulesets/AdBlock").join(name))
}

