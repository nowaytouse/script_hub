type ParsedSections = Vec<(String, Vec<(usize, String)>)>;
fn parse_sections(text: &str) -> ParsedSections {
    let mut output: ParsedSections = Vec::new();
    for (index, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if let Some(name) = line.strip_prefix('[').and_then(|s| s.strip_suffix(']')) {
            output.push((name.into(), Vec::new()));
        } else if !line.is_empty()
            && !line.starts_with(['#', ';'])
            && !line.starts_with("//")
            && let Some((_, rows)) = output.last_mut()
        {
            rows.push((index + 1, line.into()));
        }
    }
    output
}

/// Split fields without treating commas inside quoted regexes or logical groups as separators.
fn fields(text: &str) -> Option<Vec<String>> {
    let logical = ["AND,", "OR,", "NOT,", "("]
        .iter()
        .any(|p| text.trim_start().starts_with(p));
    let mut result = Vec::new();
    let mut current = String::new();
    let mut quoted = false;
    let mut escaped = false;
    let mut depth = 0usize;
    for c in text.chars() {
        if escaped {
            current.push(c);
            escaped = false;
            continue;
        }
        if c == '\\' {
            current.push(c);
            escaped = true;
            continue;
        }
        if c == '"' {
            quoted = !quoted;
            current.push(c);
            continue;
        }
        if !quoted {
            if logical {
                match c {
                    '(' => depth += 1,
                    ')' => depth = depth.checked_sub(1)?,
                    _ => {}
                }
            }
            if c == ',' && depth == 0 {
                result.push(unquote_field(&current));
                current.clear();
                continue;
            }
        }
        current.push(c);
    }
    if quoted || depth != 0 {
        return None;
    }
    result.push(unquote_field(&current));
    Some(result)
}
fn unquote_field(value: &str) -> String {
    let value = value.trim();
    value
        .strip_prefix('"')
        .and_then(|s| s.strip_suffix('"'))
        .unwrap_or(value)
        .to_owned()
}
fn quoted_field(value: &str) -> String {
    if value.contains(',') || value.chars().any(char::is_whitespace) {
        format!("\"{}\"", value.replace('"', "\\\""))
    } else {
        value.into()
    }
}
fn policy(value: &str) -> Option<&str> {
    match value {
        "DIRECT" => Some("DIRECT"),
        "REJECT-DROP" => Some("REJECT-DROP"),
        "REJECT" | "REJECT-NO-DROP" | "REJECT-TINYGIF" | "REJECT-IMG" | "REJECT-DICT"
        | "REJECT-ARRAY" | "REJECT-200" => Some("REJECT"),
        _ => None,
    }
}
fn leaf(parts: &[String], nested: bool) -> Option<String> {
    if parts.len() != 2 || parts[1].is_empty() {
        return None;
    }
    let kind = parts[0].as_str();
    if matches!(kind, "AND" | "OR" | "NOT") {
        let group = parts[1].strip_prefix('(')?.strip_suffix(')')?;
        let children = fields(group)?;
        if children.is_empty() || kind == "NOT" && children.len() != 1 {
            return None;
        }
        let children = children
            .iter()
            .map(|child| {
                let child = child.strip_prefix('(')?.strip_suffix(')')?;
                Some(format!("({})", leaf(&fields(child)?, true)?))
            })
            .collect::<Option<Vec<_>>>()?;
        return Some(format!("{kind},({})", children.join(",")));
    }
    if kind == "PROTOCOL" {
        return (nested && matches!(parts[1].as_str(), "TCP" | "UDP"))
            .then(|| format!("PROTOCOL,{}", parts[1]));
    }
    let kind = match kind {
        "DOMAIN" | "DOMAIN-SUFFIX" | "DOMAIN-KEYWORD" | "DOMAIN-WILDCARD" | "IP-CIDR"
        | "IP-CIDR6" | "SRC-IP-CIDR" | "SRC-PORT" | "IN-PORT" | "PROCESS-NAME" => kind,
        "SRC-IP" => "SRC-IP-CIDR",
        "DEST-PORT" | "DST-PORT" => "DEST-PORT",
        _ => return None,
    };
    Some(format!("{kind},{}", quoted_field(&parts[1])))
}
fn emit_rule(
    line: &str,
    number: usize,
    report: &mut Projection,
    output: &mut BTreeMap<String, Vec<String>>,
) {
    let Some(parts) = fields(line) else {
        report.note(number, "Rule", "omitted", "unbalanced rule fields");
        return;
    };
    if parts.len() < 3 {
        report.note(
            number,
            "Rule",
            "omitted",
            "rule needs matcher, payload and a supported built-in policy",
        );
        return;
    }
    let Some(target_policy) = policy(&parts[2]) else {
        report.note(number, "Rule", "omitted", "unsupported named/group policy");
        return;
    };
    if parts[0] == "URL-REGEX" {
        let action = match parts[2].as_str() {
            "REJECT-IMG" | "REJECT-TINYGIF" => "reject-img",
            "REJECT-DICT" => "reject-dict",
            "REJECT-ARRAY" => "reject-array",
            "REJECT-200" => "reject-200",
            "DIRECT" => {
                report.note(
                    number,
                    "Rule",
                    "omitted",
                    "URL-REGEX DIRECT cannot become a rejecting rewrite",
                );
                return;
            }
            _ => "reject",
        };
        if parts[1].chars().any(char::is_whitespace) {
            report.note(
                number,
                "Rule",
                "omitted",
                "URL regex contains whitespace unsupported by native rewrite tokenization",
            );
            return;
        }
        output
            .entry("URL Rewrite".into())
            .or_default()
            .push(format!("{} {action}", parts[1]));
        report.note(
            number,
            "Rule",
            "adapted",
            "URL-REGEX converted to native URL Rewrite",
        );
        return;
    }
    let Some(matcher) = leaf(&parts[..2], false) else {
        report.note(
            number,
            "Rule",
            "omitted",
            format!(
                "unsupported matcher {} (use the main Mihomo providers where applicable)",
                parts[0]
            ),
        );
        return;
    };
    let keep_no_resolve = matches!(parts[0].as_str(), "IP-CIDR" | "IP-CIDR6")
        && parts[3..]
            .iter()
            .any(|o| o.eq_ignore_ascii_case("no-resolve"));
    let dropped = parts[3..]
        .iter()
        .filter(|o| !(keep_no_resolve && o.eq_ignore_ascii_case("no-resolve")))
        .cloned()
        .collect::<Vec<_>>();
    if !dropped.is_empty() {
        report.note(
            number,
            "Rule",
            "adapted",
            format!(
                "importer does not preserve rule options: {}",
                dropped.join(",")
            ),
        );
    }
    if target_policy != parts[2] {
        report.note(
            number,
            "Rule",
            "adapted",
            format!("{} becomes {target_policy} in the importer", parts[2]),
        );
    }
    output.entry("Rule".into()).or_default().push(format!(
        "{matcher},{target_policy}{}",
        if keep_no_resolve { ",no-resolve" } else { "" }
    ));
}
fn script(line: &str, number: usize, report: &mut Projection) -> Option<String> {
    let (name, parameters) = line.split_once('=')?;
    let mut values = Vec::new();
    for field in crate::smart_cleanup::split_script_parameters(parameters) {
        let (key, value) = field.split_once('=')?;
        if values.iter().any(|(existing, _)| *existing == key.trim()) {
            report.note(
                number,
                "Script",
                "omitted",
                "duplicate script parameter requires explicit review",
            );
            return None;
        }
        values.push((key.trim(), value.trim()));
    }
    let value = |key| {
        values
            .iter()
            .find_map(|(k, v)| (*k == key).then_some(v.trim_matches(['\'', '"'])))
    };
    let kind = value("type")?;
    if value("enable") == Some("false") {
        report.note(number, "Script", "omitted", "disabled script");
        return None;
    }
    if !matches!(
        kind,
        "http-request" | "http-response" | "cron" | "event" | "generic"
    ) {
        report.note(
            number,
            "Script",
            "omitted",
            format!("unsupported script type {kind}"),
        );
        return None;
    }
    let path = value("script-path")?.trim_matches(['\'', '"']);
    if !path.starts_with("https://") {
        report.note(
            number,
            "Script",
            "omitted",
            "remote module requires an HTTPS script resource, not a local attachment",
        );
        return None;
    }
    if kind.starts_with("http-") && value("pattern").is_none()
        || kind == "cron" && value("cronexp").is_none()
    {
        report.note(
            number,
            "Script",
            "omitted",
            "missing required pattern/cronexp",
        );
        return None;
    }
    if kind == "event"
        && !matches!(
            value("event-name"),
            Some("network-changed" | "engine-started" | "profile-reloaded")
        )
    {
        report.note(number, "Script", "omitted", "unsupported event-name");
        return None;
    }
    let allowed = [
        "type",
        "pattern",
        "cronexp",
        "event-name",
        "script-path",
        "requires-body",
        "binary-body-mode",
        "max-size",
        "timeout",
        "full-header-mode",
        "argument",
        "enable",
    ];
    let mut kept = Vec::new();
    for (key, value) in values {
        if allowed.contains(&key) {
            kept.push(format!("{key}={value}"));
        } else {
            report.note(
                number,
                "Script",
                "adapted",
                format!("importer does not forward script field {key}"),
            );
        }
    }
    Some(format!("{} = {}", name.trim(), kept.join(", ")))
}
fn map_local(line: &str) -> Option<String> {
    let values = crate::rewrite_syntax::parse_strict(line).ok()?;
    let get = |key: &str| values.iter().find_map(|v| v.strip_prefix(key));
    if get("data-type=") == Some("tiny-gif") {
        if get("data=").is_some() {
            return None;
        }
        let mut result = quoted_field(values.first()?);
        for item in values.iter().skip(1) {
            let (key, value) = item.split_once('=')?;
            if key == "data-type" {
                result.push_str(r#" data-type=base64 data="R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7""#);
            } else {
                result.push_str(&format!(
                    " {key}={}",
                    crate::rewrite_syntax::quote_field(value).ok()?
                ));
            }
        }
        if get("header=").is_none() {
            result.push_str(r#" header="Content-Type:image/gif""#);
        }
        return Some(result);
    }
    let data = get("data=")?;
    let supported = match get("data-type=").unwrap_or("file") {
        "file" => data.starts_with("https://"),
        "text" | "base64" => true,
        _ => false,
    };
    supported.then(|| line.to_owned())
}

/// Project a public Surge artifact into the pinned preview importer's supported input.
fn argument_defaults(source: &str) -> Result<BTreeMap<String, String>, String> {
    let meta = crate::merge_bundles::module_metadata_pub(source);
    let mut defaults = BTreeMap::new();
    if let Some(arguments) = meta.get("arguments") {
        for field in crate::smart_cleanup::split_script_parameters(arguments) {
            let (key, value) = field
                .split_once(':')
                .ok_or("invalid public argument default")?;
            let value = value.trim();
            let value = if value.starts_with('"') {
                serde_json::from_str::<String>(value)
                    .map_err(|_| "invalid quoted argument default")?
            } else {
                value.trim_matches('\'').into()
            };
            if defaults.insert(key.trim().to_owned(), value).is_some() {
                return Err("duplicate public argument default".into());
            }
        }
    }
    Ok(defaults)
}
fn resolve_defaults(line: &str, defaults: &BTreeMap<String, String>) -> Option<String> {
    let mut rest = line;
    let mut out = String::new();
    while let Some((before, tail)) = rest.split_once("{{{") {
        let (key, after) = tail.split_once("}}}")?;
        out.push_str(before);
        out.push_str(defaults.get(key)?);
        rest = after;
    }
    out.push_str(rest);
    (!out.contains("{{{") && !out.contains("}}}")).then_some(out)
}

