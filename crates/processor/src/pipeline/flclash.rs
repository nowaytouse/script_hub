fn render_routing(
    source: &str,
    _name: &str,
    target: &str,
    options: &[String],
) -> Result<Projection, String> {
    policy(target).ok_or("PROMAX routing source has an unsupported policy")?;
    let mut report = Projection {
        content: String::new(),
        input_lines: 0,
        emitted_lines: 0,
        active_lines: 0,
        sections: BTreeMap::new(),
        diagnostics: Vec::new(),
    };
    let discarded = options
        .iter()
        .filter(|option| !option.eq_ignore_ascii_case("no-resolve"))
        .cloned()
        .collect::<BTreeSet<_>>();
    if !discarded.is_empty() {
        report.note(
            0,
            "Rule",
            "adapted",
            format!(
                "parent RULE-SET options are not preserved: {}",
                discarded.into_iter().collect::<Vec<_>>().join(",")
            ),
        );
    }
    let parent_no_resolve = options
        .iter()
        .any(|option| option.eq_ignore_ascii_case("no-resolve"));
    let mut output = BTreeMap::new();
    for (number, raw) in source.lines().enumerate() {
        let row = raw.trim();
        if row.is_empty() || row.starts_with(['#', ';']) || row.starts_with("//") {
            continue;
        }
        report.input_lines += 1;
        let mut parts = fields(row).ok_or("malformed public PROMAX ruleset row")?;
        if parts.len() < 2 || parts[0] == "RULE-SET" {
            return Err("invalid or nested public PROMAX ruleset row".into());
        }
        parts.insert(2, target.into());
        if parent_no_resolve
            && matches!(parts[0].as_str(), "IP-CIDR" | "IP-CIDR6")
            && !parts[3..]
                .iter()
                .any(|option| option.eq_ignore_ascii_case("no-resolve"))
        {
            parts.push("no-resolve".into());
        }
        emit_rule(
            &parts
                .iter()
                .map(|part| quoted_field(part))
                .collect::<Vec<_>>()
                .join(","),
            number + 1,
            &mut report,
            &mut output,
        );
    }
    append_sections(&mut report, &mut output);
    if report.content.len() > MAX_ROUTING_SHARD_BYTES {
        return Err("PROMAX routing output exceeds the per-shard publication limit".into());
    }
    Ok(report)
}

fn plan_promax_routing(root: &Path, source: &str) -> Result<Vec<RoutingReport>, String> {
    let parsed = parse_sections(source);
    let inline = parsed
        .iter()
        .filter_map(|(name, _)| name.strip_prefix("Ruleset "))
        .collect::<BTreeSet<_>>();
    let mut reports = Vec::new();
    let mut seen = BTreeSet::new();
    let mut source_bytes = 0usize;
    let mut output_bytes = 0usize;
    for (_, rows) in parsed.iter().filter(|(name, _)| name == "Rule") {
        for (number, line) in rows {
            let parts = fields(line).ok_or("malformed PROMAX source rule")?;
            if parts.first().is_none_or(|kind| kind != "RULE-SET") {
                continue;
            }
            let url = parts.get(1).ok_or("PROMAX RULE-SET lacks source")?;
            if inline.contains(url.as_str()) {
                continue;
            }
            let rel = public_adblock_path(url)?;
            if !seen.insert(rel.clone()) {
                return Err("duplicate PROMAX routing source requires explicit review".into());
            }
            let target = parts.get(2).ok_or("PROMAX RULE-SET lacks policy")?;
            let text = read_public_bounded(root, &root.join(&rel), MAX_ROUTING_SHARD_BYTES)?;
            source_bytes += text.len();
            if source_bytes > MAX_ROUTING_TOTAL_BYTES {
                return Err("PROMAX routing inputs exceed the total publication limit".into());
            }
            let stem = rel
                .file_stem()
                .and_then(|stem| stem.to_str())
                .ok_or("invalid PROMAX source filename")?;
            let projection = render_routing(&text, stem, target, &parts[3..])?;
            output_bytes += projection.content.len();
            if output_bytes > MAX_ROUTING_TOTAL_BYTES {
                return Err("PROMAX routing outputs exceed the total publication limit".into());
            }
            reports.push(RoutingReport {
                source: relative(root, &root.join(&rel))?,
                source_bytes: text.len(),
                source_rule_line: *number,
                source_policy: target.clone(),
                source_options: parts[3..].to_vec(),
                source_md5_change_fingerprint: fingerprint(&text),
                embedded_in: (projection.active_lines > 0).then(|| MAIN_MODULE.to_owned()),
                projected_bytes: projection.content.len(),
                projection,
            });
        }
    }
    Ok(reports)
}

fn plan(root: &Path) -> Result<BTreeMap<PathBuf, String>, String> {
    let source = root.join("modules/surge");
    let mut paths = Vec::new();
    for entry in walkdir::WalkDir::new(&source) {
        let entry = entry.map_err(|e| e.to_string())?;
        if entry.file_type().is_symlink() {
            return Err("symlink in Surge publication".into());
        }
        if entry.file_type().is_file()
            && entry.path().extension().is_some_and(|e| e == "sgmodule")
            && !entry.path().components().any(|p| p.as_os_str() == "github")
        {
            paths.push(entry.path().to_owned());
        }
    }
    paths.sort();
    if paths.is_empty() {
        return Err("no public Surge modules to project".into());
    }
    let mut outputs = BTreeMap::new();
    let mut modules = Vec::new();
    let mut promax_routing = Vec::new();
    for path in paths {
        let rel = path.strip_prefix(&source).map_err(|e| e.to_string())?;
        if !rel
            .components()
            .next()
            .is_some_and(|p| CATEGORIES.iter().any(|c| p.as_os_str() == *c))
        {
            return Err("unexpected Surge category".into());
        }
        let text = read_public(root, &path)?;
        if path.file_name().is_some_and(|name| name == PROMAX) {
            if !promax_routing.is_empty() {
                return Err("multiple PROMAX routing sources require explicit review".into());
            }
            promax_routing = plan_promax_routing(root, &text)?;
        }
        let projection = if path.file_name().is_some_and(|name| name == PROMAX) {
            render_embedded(&text, &promax_routing)?
        } else {
            render(&text)?
        };
        let (target, mirror) = if projection.active_lines > 0 {
            let mut rel = rel.to_path_buf();
            if path.file_name().is_some_and(|n| n == PROMAX) {
                rel.set_file_name("ScriptHub.AdBlock.Preview.sgmodule");
            }
            let target = root.join(ROOT).join(&rel);
            let parent = rel.parent().ok_or("module has no category")?;
            let mirror = root
                .join(ROOT)
                .join(parent)
                .join("github")
                .join(rel.file_name().ok_or("module filename missing")?);
            let raw = crate::url_rewriter::github_urls(&projection.content);
            outputs.insert(target.clone(), projection.content.clone());
            outputs.insert(mirror.clone(), raw);
            (
                Some(relative(root, &target)?),
                Some(relative(root, &mirror)?),
            )
        } else {
            (None, None)
        };
        modules.push(ModuleReport {
            source: relative(root, &path)?,
            source_md5_change_fingerprint: fingerprint(&text),
            install_url: target
                .as_ref()
                .filter(|_| projection.content.len() <= 20_000_000)
                .map(|p| {
                    format!(
                        "https://cdn.jsdelivr.net/gh/nowaytouse/script_hub@master/{}",
                        encode(p)
                    )
                }),
            github_install_url: mirror.as_ref().map(|p| {
                format!(
                    "https://raw.githubusercontent.com/nowaytouse/script_hub/master/{}",
                    encode(p)
                )
            }),
            path: target,
            github_path: mirror,
            projection,
        });
    }
    let catalog = Catalog {
        schema_version: 3,
        target: "FlClash preview 0.9.4+2026111517",
        importer_revision: CONTRACT_REVISION,
        importer_blob: IMPORTER_BLOB,
        importer_test_blob: IMPORTER_TEST_BLOB,
        importer_source: format!(
            "https://github.com/chen08209/FlClash/blob/{CONTRACT_REVISION}/lib/common/mitm_module.dart"
        ),
        fingerprint_purpose: "MD5 is a non-security source-change fingerprint only; it is not download authentication",
        validation_scope: "Static importer compatibility and deterministic source/output equality only; no script API, endpoint, certificate or live MITM execution acceptance",
        external_rulesets: "Native importer does not support remote RULE-SET. Public repository lists explicitly declared by source PROMAX are embedded in its single native module at their source positions; other external lists remain unsupported. No extra provider is injected into a template.",
        modules,
        promax_routing_note: "Source-list audit only, not separate installable modules. Supported rows are embedded into the single PROMAX module in declaration order and exact duplicate rows retain their first occurrence. Per-source counts precede aggregate deduplication. Unsupported matchers and lost Surge options are reported. Limits are 8 MiB per source list and 64 MiB for all sources and for the merged module, not verified client capacity or performance guarantees.",
        promax_routing,
    };
    outputs.insert(
        root.join(ROOT).join("catalog.json"),
        serde_json::to_string_pretty(&catalog).map_err(|e| e.to_string())? + "\n",
    );
    Ok(outputs)
}
fn existing(root: &Path) -> Result<BTreeMap<PathBuf, String>, String> {
    let dir = root.join(ROOT);
    if !dir.exists() {
        crate::verify_missing_directory(&dir)?;
        return Ok(BTreeMap::new());
    }
    let mut out = BTreeMap::new();
    for entry in walkdir::WalkDir::new(&dir) {
        let entry = entry.map_err(|e| e.to_string())?;
        if entry.file_type().is_symlink() {
            return Err("symlink in FlClash publication".into());
        }
        if entry.file_type().is_file() {
            out.insert(
                entry.path().to_path_buf(),
                read_public_bounded(root, entry.path(), MAX_ROUTING_TOTAL_BYTES)?,
            );
        }
    }
    Ok(out)
}
fn retired_owned_routing(root: &Path, path: &Path, text: &str) -> bool {
    if path.parent() != Some(root.join(ROOT).join("head_expanse").as_path())
        || !text.lines().any(|line| line == OWNER)
    {
        return false;
    }
    path.file_name()
        .and_then(|name| name.to_str())
        .and_then(|name| name.strip_prefix("ScriptHub.PROMAX."))
        .and_then(|name| name.strip_suffix(".sgmodule"))
        .is_some_and(|stem| {
            stem.starts_with("AdBlock_")
                && !stem.contains("..")
                && stem
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-'))
        })
}

/// Generate only public, native preview modules; no network, vault or user profile access.
pub fn run_generator(root: &Path) -> Result<usize, String> {
    let planned = plan(root)?;
    let old = existing(root)?;
    for (path, text) in &old {
        if !text.contains(OWNER) && !path.ends_with("catalog.json") {
            return Err(format!("unowned FlClash output {}", path.display()));
        }
        if !planned.contains_key(path) && !retired_owned_routing(root, path, text) {
            return Err(format!(
                "stale output requires explicit review (preserved): {}",
                path.display()
            ));
        }
    }
    for (path, text) in &planned {
        if old.get(path) == Some(text) {
            continue;
        }
        let parent = path.parent().ok_or("missing publication parent")?;
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        crate::filesystem::replace_file(path, text.as_bytes()).map_err(|e| e.to_string())?;
    }
    // Remove only the former generator-owned routing namespace after every new
    // artifact has been successfully written. Unknown/unowned files fail above.
    for (path, text) in &old {
        if !planned.contains_key(path) && retired_owned_routing(root, path, text) {
            fs::remove_file(path).map_err(|e| e.to_string())?;
        }
    }
    Ok(planned.len() - 1)
}
/// Recompute every output and the diagnostic catalog; detect stale, missing and altered files.
pub fn validate_generated(root: &Path) -> Result<usize, String> {
    let planned = plan(root)?;
    let old = existing(root)?;
    if planned != old {
        let bad = planned
            .iter()
            .find(|(p, s)| old.get(*p) != Some(*s))
            .map(|(p, _)| p)
            .or_else(|| old.keys().find(|p| !planned.contains_key(*p)));
        return Err(format!(
            "FlClash generated output mismatch: {}",
            bad.map(|p| p.display().to_string()).unwrap_or_default()
        ));
    }
    Ok(planned.len())
}

