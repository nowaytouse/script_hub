fn is_promax_domain(domain: &str) -> bool {
    domain.len() <= 253
        && domain.rsplit_once('.').is_some_and(|(_, suffix)| {
            suffix.bytes().all(|byte| byte.is_ascii_alphabetic()) || suffix.starts_with("xn--")
        })
        && domain.split('.').all(|label| {
            !label.is_empty()
                && label.len() <= 63
                && label
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
        })
}

fn render_routing(
    source: &str,
    target: &str,
    options: &[String],
    safety: &SafetyPolicy,
) -> Result<Projection, String> {
    if !is_block_policy(target) {
        return Err("FlClash PROMAX local ad list requires a blocking policy".into());
    }
    let mut report = Projection {
        content: String::new(),
        input_lines: 0,
        emitted_lines: 0,
        active_lines: 0,
        sections: BTreeMap::new(),
        diagnostics: Vec::new(),
    };
    let discarded = options
        .iter()
        .filter(|option| !option.eq_ignore_ascii_case("no-resolve"))
        .cloned()
        .collect::<BTreeSet<_>>();
    if !discarded.is_empty() {
        report.note(
            0,
            "Rule",
            "adapted",
            format!(
                "parent RULE-SET options are not preserved: {}",
                discarded.into_iter().collect::<Vec<_>>().join(",")
            ),
        );
    }
    let mut output = BTreeMap::new();
    for (number, raw) in source.lines().enumerate() {
        let row = raw.trim();
        if row.is_empty() || row.starts_with(['#', ';']) || row.starts_with("//") {
            continue;
        }
        report.input_lines += 1;
        let parts = fields(row).ok_or("malformed public PROMAX ruleset row")?;
        if let [kind, domain] = parts.as_slice()
            && matches!(kind.as_str(), "DOMAIN" | "DOMAIN-SUFFIX")
            && is_promax_domain(domain)
        {
            let domain = domain.to_ascii_lowercase();
            let line = format!(
                "{kind},{domain},{}",
                policy(target).expect("validated policy")
            );
            let rule = SurgeRule::parse(&line).map_err(|error| error.to_string())?;
            if safety.decision(&rule) != SafetyDecision::Keep
                || PUBLIC_DOH_BOOTSTRAPS.iter().any(|(host, _)| {
                    *host == domain
                        || kind == "DOMAIN-SUFFIX"
                            && host
                                .strip_suffix(&domain)
                                .is_some_and(|prefix| prefix.ends_with('.'))
                })
            {
                report.note(
                    number + 1,
                    "Rule",
                    "omitted",
                    "Protected service or encrypted resolver",
                );
            } else {
                output
                    .entry("Rule".into())
                    .or_insert_with(Vec::new)
                    .push(line);
            }
        } else {
            report.note(
                number + 1,
                "Rule",
                "omitted",
                "Only exact domains and dotted domain suffixes are retained for FlClash PROMAX",
            );
        }
    }
    append_sections(&mut report, &output);
    validate_promax_load_budget(report.content.len(), report.active_lines)?;
    Ok(report)
}

fn plan_promax_routing(root: &Path, source: &str) -> Result<Vec<RoutingReport>, String> {
    let whitelist = read_public(root, &root.join(PROMAX_WHITELIST))?;
    let safety = SafetyPolicy::from_lines(
        whitelist
            .lines()
            .chain(PROMAX_PROTECTED_SERVICE_HOSTS.iter().copied()),
    );
    let parsed = parse_sections(source);
    let inline = parsed
        .iter()
        .filter_map(|(name, _)| name.strip_prefix("Ruleset "))
        .collect::<BTreeSet<_>>();
    let mut reports = Vec::new();
    let mut seen = BTreeSet::new();
    for (_, rows) in parsed.iter().filter(|(name, _)| name == "Rule") {
        for (number, line) in rows {
            let parts = fields(line).ok_or("malformed PROMAX source rule")?;
            if parts.first().is_none_or(|kind| kind != "RULE-SET") {
                continue;
            }
            let url = parts.get(1).ok_or("PROMAX RULE-SET lacks source")?;
            if inline.contains(url.as_str()) {
                continue;
            }
            let rel = public_adblock_path(url)?;
            if !PROMAX_DOMAIN_LISTS
                .iter()
                .any(|path| rel == Path::new(path))
            {
                continue;
            }
            if !seen.insert(rel.clone()) {
                return Err("duplicate FlClash PROMAX domain list declaration".into());
            }
            let target = parts.get(2).ok_or("PROMAX RULE-SET lacks policy")?;
            let text = read_public_bounded(root, &root.join(&rel), MAX_PROMAX_SOURCE_BYTES)?;
            let projection = render_routing(&text, target, &parts[3..], &safety)?;
            if projection.active_lines == 0 {
                return Err(format!(
                    "FlClash PROMAX domain list has no eligible rules: {}",
                    rel.display()
                ));
            }
            reports.push(RoutingReport {
                source: relative(root, &root.join(&rel))?,
                source_bytes: text.len(),
                source_rule_line: *number,
                source_policy: target.clone(),
                source_options: parts[3..].to_vec(),
                source_md5_change_fingerprint: fingerprint(&text),
                embedded_in: (projection.active_lines > 0).then(|| MAIN_MODULE.to_owned()),
                projected_bytes: projection.content.len(),
                projection,
            });
        }
    }
    if !seen.contains(Path::new(PROMAX_AD_LIST)) {
        return Err("FlClash PROMAX requires a nonempty source-declared local app ad list".into());
    }
    Ok(reports)
}

fn plan(root: &Path) -> Result<BTreeMap<PathBuf, String>, String> {
    let source = root.join("modules/surge");
    let mut paths = Vec::new();
    for entry in walkdir::WalkDir::new(&source) {
        let entry = entry.map_err(|e| e.to_string())?;
        if entry.file_type().is_symlink() {
            return Err("symlink in Surge publication".into());
        }
        if entry.file_type().is_file()
            && entry.path().extension().is_some_and(|e| e == "sgmodule")
            && !entry.path().components().any(|p| p.as_os_str() == "github")
        {
            paths.push(entry.path().to_owned());
        }
    }
    paths.sort();
    if paths.is_empty() {
        return Err("no public Surge modules to project".into());
    }
    let mut outputs = BTreeMap::new();
    let mut modules = Vec::new();
    let mut promax_routing = Vec::new();
    let firewall_path = Path::new("head_expanse").join(FIREWALL_SURGE_FILE);
    let helper_path = Path::new("head_expanse").join(HELPER_SURGE_FILE);
    let mut retired_firewall = BTreeSet::new();
    for path in paths {
        let rel = path.strip_prefix(&source).map_err(|e| e.to_string())?;
        if !rel
            .components()
            .next()
            .is_some_and(|p| CATEGORIES.iter().any(|c| p.as_os_str() == *c))
        {
            return Err("unexpected Surge category".into());
        }
        let text = read_public(root, &path)?;
        if rel == firewall_path {
            let projection = render(&text)?;
            let sections = parse_sections(&projection.content);
            let [(section, rows)] = sections.as_slice() else {
                return Err("Retired FlClash firewall source is not a port-only module".into());
            };
            if section != "Rule"
                || rows.iter().any(|(_, row)| {
                    !row.split_once(',')
                        .is_some_and(|(kind, _)| is_port_rule(kind))
                })
            {
                return Err("Retired FlClash firewall source is not a port-only module".into());
            }
            retired_firewall.extend(rows.iter().map(|(_, row)| row.clone()));
            continue;
        }
        if path.file_name().is_some_and(|name| name == PROMAX) {
            if !promax_routing.is_empty() {
                return Err("multiple PROMAX routing sources require explicit review".into());
            }
            promax_routing = plan_promax_routing(root, &text)?;
        }
        let projection = if path.file_name().is_some_and(|name| name == PROMAX) {
            render_embedded(&text, Some(&promax_routing))?
        } else if rel == helper_path {
            render_helper(&text)?
        } else {
            render(&text)?
        };
        let (target, mirror) = if projection.active_lines > 0 {
            let mut rel = rel.to_path_buf();
            if path.file_name().is_some_and(|n| n == PROMAX) {
                rel.set_file_name("ScriptHub.AdBlock.Preview.sgmodule");
            } else if rel == helper_path {
                rel.set_file_name(HELPER_MODULE_NAME);
            }
            let target = root.join(ROOT).join(&rel);
            let parent = rel.parent().ok_or("module has no category")?;
            let mirror = root
                .join(ROOT)
                .join(parent)
                .join("github")
                .join(rel.file_name().ok_or("module filename missing")?);
            let raw = crate::url_rewriter::github_urls(&projection.content);
            outputs.insert(target.clone(), projection.content.clone());
            outputs.insert(mirror.clone(), raw);
            (
                Some(relative(root, &target)?),
                Some(relative(root, &mirror)?),
            )
        } else {
            (None, None)
        };
        modules.push(ModuleReport {
            source: relative(root, &path)?,
            source_md5_change_fingerprint: fingerprint(&text),
            install_url: target
                .as_ref()
                .filter(|_| projection.content.len() <= 20_000_000)
                .map(|p| {
                    format!(
                        "https://cdn.jsdelivr.net/gh/nowaytouse/script_hub@master/{}",
                        encode(p)
                    )
                }),
            github_install_url: mirror.as_ref().map(|p| {
                format!(
                    "https://raw.githubusercontent.com/nowaytouse/script_hub/master/{}",
                    encode(p)
                )
            }),
            path: target,
            github_path: mirror,
            projection,
        });
    }
    if !retired_firewall.is_empty() {
        let promax = outputs
            .get(&root.join(MAIN_MODULE))
            .ok_or("Cannot retire the standalone FlClash firewall without PROMAX")?;
        let retained = promax
            .lines()
            .filter(|row| retired_firewall.contains(*row))
            .collect::<BTreeSet<_>>();
        if retained.len() != retired_firewall.len() {
            return Err("PROMAX is missing a supported standalone FlClash firewall rule".into());
        }
    }
    let catalog = Catalog {
        schema_version: 3,
        target: "FlClash preview 0.9.4+2026111517",
        importer_revision: CONTRACT_REVISION,
        importer_blob: IMPORTER_BLOB,
        importer_test_blob: IMPORTER_TEST_BLOB,
        importer_source: format!(
            "https://github.com/chen08209/FlClash/blob/{CONTRACT_REVISION}/lib/common/mitm_module.dart"
        ),
        fingerprint_purpose: "MD5 is a non-security source-change fingerprint only; it is not download authentication",
        validation_scope: "Static importer compatibility and deterministic source/output equality only; no script API, endpoint, certificate or live MITM execution acceptance",
        external_rulesets: "For the pinned preview importer, Compatibility PROMAX embeds exact domains and dotted suffixes from approved source-declared advertising, privacy and threat lists. No extra provider is injected into a template.",
        modules,
        promax_routing_note: "Compatibility PROMAX combines app and general advertising, Anti-AD, privacy, HaGeZi TIF Medium and supplemental threat domains with firewall ports and reviewed native HTTP handlers scoped to exact MITM hosts. Exact duplicates retain their first occurrence. The module is capped at 36 MiB and 850,000 active entries.",
        promax_routing,
    };
    outputs.insert(
        root.join(ROOT).join("catalog.json"),
        serde_json::to_string_pretty(&catalog).map_err(|e| e.to_string())? + "\n",
    );
    Ok(outputs)
}
fn existing(root: &Path) -> Result<BTreeMap<PathBuf, String>, String> {
    let dir = root.join(ROOT);
    if !dir.exists() {
        crate::verify_missing_directory(&dir)?;
        return Ok(BTreeMap::new());
    }
    let mut out = BTreeMap::new();
    for entry in walkdir::WalkDir::new(&dir) {
        let entry = entry.map_err(|e| e.to_string())?;
        if entry.file_type().is_symlink() {
            return Err("symlink in FlClash publication".into());
        }
        if entry.file_type().is_file() {
            out.insert(
                entry.path().to_path_buf(),
                read_public_bounded(root, entry.path(), MAX_EXISTING_ARTIFACT_BYTES)?,
            );
        }
    }
    Ok(out)
}
fn retired_owned_output(root: &Path, path: &Path, text: &str) -> bool {
    if !text.lines().any(|line| line == OWNER) {
        return false;
    }
    let head = root.join(ROOT).join("head_expanse");
    if path == head.join(FIREWALL_SURGE_FILE)
        || path == head.join("github").join(FIREWALL_SURGE_FILE)
    {
        return true;
    }
    if path.parent() != Some(head.as_path()) {
        return false;
    }
    path.file_name()
        .and_then(|name| name.to_str())
        .and_then(|name| name.strip_prefix("ScriptHub.PROMAX."))
        .and_then(|name| name.strip_suffix(".sgmodule"))
        .is_some_and(|stem| {
            stem.starts_with("AdBlock_")
                && !stem.contains("..")
                && stem
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-'))
        })
}

/// Generate only public, native preview modules; no network, vault or user profile access.
pub fn run_generator(root: &Path) -> Result<usize, String> {
    let planned = plan(root)?;
    for (path, content) in &planned {
        if path.extension().is_some_and(|ext| ext == "sgmodule") {
            validate_native_rewrites(content)?;
        }
    }
    let old = existing(root)?;
    for (path, text) in &old {
        if !text.contains(OWNER) && !path.ends_with("catalog.json") {
            return Err(format!("unowned FlClash output {}", path.display()));
        }
        if !planned.contains_key(path) && !retired_owned_output(root, path, text) {
            return Err(format!(
                "stale output requires explicit review (preserved): {}",
                path.display()
            ));
        }
    }
    for (path, text) in &planned {
        if old.get(path) == Some(text) {
            continue;
        }
        let parent = path.parent().ok_or("missing publication parent")?;
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        crate::filesystem::replace_file(path, text.as_bytes()).map_err(|e| e.to_string())?;
    }
    // Remove only the retired generator-owned outputs after every new
    // artifact has been successfully written. Unknown/unowned files fail above.
    for (path, text) in &old {
        if !planned.contains_key(path) && retired_owned_output(root, path, text) {
            fs::remove_file(path).map_err(|e| e.to_string())?;
        }
    }
    Ok(planned.len() - 1)
}
/// Recompute every output and the diagnostic catalog; detect stale, missing and altered files.
pub fn validate_generated(root: &Path) -> Result<usize, String> {
    let planned = plan(root)?;
    let old = existing(root)?;
    // An equal recomputation can repeat a compiler bug. Validate the produced
    // target syntax independently of the source/output equality check.
    for (path, content) in &old {
        if path.extension().is_some_and(|ext| ext == "sgmodule") {
            validate_native_rewrites(content)?;
        }
    }
    if planned != old {
        let bad = planned
            .iter()
            .find(|(p, s)| old.get(*p) != Some(*s))
            .map(|(p, _)| p)
            .or_else(|| old.keys().find(|p| !planned.contains_key(*p)));
        return Err(format!(
            "FlClash generated output mismatch: {}",
            bad.map(|p| p.display().to_string()).unwrap_or_default()
        ));
    }
    Ok(planned.len())
}

fn validate_native_rewrites(content: &str) -> Result<(), String> {
    let defaults = argument_defaults(content)?;
    let mut section = "";
    for (index, row) in content.lines().enumerate() {
        let row = row.trim();
        if row.starts_with('[') && row.ends_with(']') {
            section = &row[1..row.len() - 1];
            continue;
        }
        if matches!(
            section,
            "Body Rewrite" | "Header Rewrite" | "URL Rewrite" | "Map Local"
        ) && !row.is_empty()
            && !row.starts_with('#')
        {
            let number = index + 1;
            let resolved =
                resolve_defaults(row, &defaults).ok_or("Unresolved target rewrite argument")?;
            if resolved.trim_start().starts_with('#') {
                continue;
            }
            if let Some(error) =
                crate::promax::validation::validate_published_rewrite(section, &resolved).first()
            {
                return Err(format!(
                    "Invalid FlClash {section} line {number}: {}",
                    error.code
                ));
            }
        }
    }
    Ok(())
}

