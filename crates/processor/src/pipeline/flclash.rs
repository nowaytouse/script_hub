fn reviewed_promax_http(section: &str, line: &str) -> Option<(String, String)> {
    let prefix = if section == "Body Rewrite" {
        "http-response "
    } else {
        ""
    };
    let (pattern, tail) = line.strip_prefix(prefix)?.split_once(char::is_whitespace)?;
    let tail = tail.trim();
    let pattern = pattern.replace(r"\/", "/");
    let (scheme, rest) = pattern.split_once("://")?;
    if !matches!(scheme, "^https" | "^https?") {
        return None;
    }
    let (escaped_host, _) = rest.split_once('/')?;
    let host = escaped_host.replace(r"\.", ".");
    if host.replace('.', r"\.") != escaped_host
        || !is_promax_domain(&host)
        || crate::mitm_manager::is_restricted(&host)
    {
        return None;
    }
    let path = &rest[escaped_host.len()..];
    let expected = PROMAX_HTTP_RECIPES.lines().find_map(|row| {
        let mut columns = row.splitn(4, '\t');
        (columns.next()? == section && columns.next()? == host && columns.next()? == path)
            .then(|| columns.next())
            .flatten()
    })?;
    let action = match section {
        "URL Rewrite"
            if tail == expected
                || tail.strip_prefix("_ ") == Some(expected)
                || tail.strip_prefix("- ") == Some(expected) =>
        {
            expected
        }
        "Map Local" => reviewed_promax_map(tail, expected)?,
        "Body Rewrite" if tail == expected => expected,
        _ => return None,
    };
    let boundary =
        if path.ends_with(['/', '$']) || path.ends_with(r"\?") || path.ends_with(r"(?:\?|$)") {
            ""
        } else if path.contains(r"\?") {
            r"(?:[&#]|$)"
        } else {
            r"(?:[?#]|$)"
        };
    let pattern = format!("{pattern}{boundary}");
    regex::Regex::new(&pattern).ok()?;
    Some((host, format!("{prefix}{pattern} {action}")))
}

fn reviewed_promax_map(tail: &str, expected: &str) -> Option<&'static str> {
    if expected == "inline-json" {
        let mut actual = tail.split_ascii_whitespace().collect::<Vec<_>>();
        actual.sort_unstable();
        let mut fields = PROMAX_INLINE_JSON
            .split_ascii_whitespace()
            .collect::<Vec<_>>();
        fields.sort_unstable();
        return (actual == fields).then_some(PROMAX_INLINE_JSON);
    }
    let data = tail.strip_prefix("data-type=file ").unwrap_or(tail);
    let url = data.strip_prefix("data=\"")?.strip_suffix('"')?;
    let name = url
        .strip_prefix("https://cdn.jsdelivr.net/gh/nowaytouse/script_hub@master/modules/source/mocks/")
        .or_else(|| url.strip_prefix("https://raw.githubusercontent.com/nowaytouse/script_hub/master/modules/source/mocks/"))?;
    if name != expected {
        return None;
    }
    match name {
        "reject-dict.json"
            if include_str!("../../../../modules/source/mocks/reject-dict.json") == "{}" =>
        {
            Some(PROMAX_INLINE_JSON)
        }
        "reject-200.txt"
            if include_str!("../../../../modules/source/mocks/reject-200.txt") == "  " =>
        {
            Some(PROMAX_INLINE_EMPTY)
        }
        _ => None,
    }
}

